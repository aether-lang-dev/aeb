#!/bin/sh
# Install this prebuilt aeb bundle. No compiler needed, and no `make`: the tools
# under share/aeb/tools are already target-native binaries and bin/aeb is a
# script, so installing is a copy plus a wrapper. (It must NOT run `make
# install`: that rebuilds the tools for the HOST via `ae`, undoing the
# cross-build and needing GNU make and ae on the target, the "GNU make is
# required" failure a prebuilt install exists to avoid.) It reproduces make
# install's copy phase: stage share/aeb, write the $BINDIR/aeb wrapper, and
# stamp AEB_STAMP from the shipped VERSION so `aeb --version` reads clean.
#
# Installed as install.sh at the top of each bundle by release/build-bundle.sh.
# Usage: ./install.sh [PREFIX]   (default: ~/.local)
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
PREFIX="${1:-$HOME/.local}"
BINDIR="$PREFIX/bin"; SHAREDIR="$PREFIX/share/aeb"
src="$here/share/aeb"
mkdir -p "$BINDIR" "$SHAREDIR"
cp -f "$src/aeb" "$SHAREDIR/aeb"; chmod +x "$SHAREDIR/aeb"
for d in lib tools veto sandbox; do
    [ -d "$src/$d" ] || continue
    rm -rf "$SHAREDIR/$d"; cp -R "$src/$d" "$SHAREDIR/$d"
done
# BUNDLE names the platform the prebuilt helpers in tools/ were built for;
# aeb keeps a helper stamped "prebuilt <VERSION> <BUNDLE>" only against these
# two files (the trampoline's aeb_fresh, tools/aebfresh).
for f in VERSION BUNDLE AETHER_PIN AETHER_FETCH; do
    if [ -f "$src/$f" ]; then cp -f "$src/$f" "$SHAREDIR/$f"; fi
done
printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# aeb wrapper — generated by the prebuilt-bundle install.sh' \
    "export AEB_HOME=\"$SHAREDIR\"" \
    "exec \"$SHAREDIR/aeb\" \"\$@\"" \
    > "$BINDIR/aeb"
chmod +x "$BINDIR/aeb"
VER="$( [ -f "$src/VERSION" ] && tr -d '[:space:]' < "$src/VERSION" || echo 0.0.0 )"
printf 'installed %s\nversion %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$VER" \
    > "$SHAREDIR/AEB_STAMP"
echo "aeb installed to $BINDIR/aeb (aeb $VER)"
